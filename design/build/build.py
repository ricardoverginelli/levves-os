#!/usr/bin/env python3
"""Generate every platform's copy of the Levves tokens from design/tokens/*.json.

    python3 design/build/build.py           write design/dist/
    python3 design/build/build.py --check   exit 1 if design/dist/ is out of date

The tokens are W3C DTCG JSON: a token is an object with "$value"; "$type" is inherited
from the nearest group that sets it; "{a.b}" as a whole value refers to another token.
Outputs (never edit them, change the tokens and rebuild):

    dist/tokens.css             CSS custom properties, --lv-<path>
    dist/qml/Levves/Theme.qml   QML singleton (with qmldir): Theme.<name>
    dist/qml/Levves/*.qml       the pieces in design/qml/ (Key, WindowFrame, Caps...), copied in
    dist/kotlin/Levves.kt       Compose object: Levves.<name>
    dist/levves_tokens.py       TOKENS dict and color() for Python builds
    dist/levves_qt.py           the hand-written Python pieces in design/python/ (tinted icons), copied in
    dist/android/res/values/levves_colors.xml   Android color resources: @color/levves_<name>
"""

import json
import re
import sys
from pathlib import Path

DESIGN = Path(__file__).resolve().parents[1]
TOKENS = DESIGN / "tokens"
DIST = DESIGN / "dist"
QML_PIECES = DESIGN / "qml"
PY_PIECES = DESIGN / "python"
HEADER = "Generated by design/build/build.py from design/tokens/. Don't edit: change the tokens and rebuild."
REF = re.compile(r"^\{([^{}]+)\}$")


class TokenError(Exception):
    pass


def load(folder=TOKENS):
    """Merge every token file into one tree; top-level groups must not repeat."""
    tree = {}
    for path in sorted(folder.glob("*.json")):
        data = json.loads(path.read_text())
        for key, value in data.items():
            if key.startswith("$"):
                continue
            if key in tree:
                raise TokenError(f"{path.name}: group '{key}' is already defined in another file")
            tree[key] = value
    return tree


def flatten(tree):
    """{path tuple: {"type", "value", "description"}} with $type inherited."""
    out = {}

    def walk(node, path, inherited):
        kind = node.get("$type", inherited)
        if "$value" in node:
            if kind is None:
                raise TokenError(
                    f"{'.'.join(path)} has no $type (set it on the token or a group above)"
                )
            out[path] = {
                "type": kind,
                "value": node["$value"],
                "description": node.get("$description", ""),
            }
            return
        for key, child in node.items():
            if not key.startswith("$") and isinstance(child, dict):
                walk(child, path + (key,), kind)

    for key, node in tree.items():
        walk(node, (key,), None)
    return out


def resolve(tokens):
    """Replace "{a.b}" references with the token they point to (chains allowed, cycles not)."""

    def value_of(path, seen):
        token = tokens[path]
        value = token["value"]
        match = REF.match(value) if isinstance(value, str) else None
        if not match:
            return value
        target = tuple(match.group(1).split("."))
        if target not in tokens:
            raise TokenError(f"{'.'.join(path)} refers to {match.group(1)}, which doesn't exist")
        if target in seen:
            raise TokenError(
                f"reference cycle: {' -> '.join('.'.join(p) for p in seen + [target])}"
            )
        if tokens[target]["type"] != token["type"]:
            raise TokenError(
                f"{'.'.join(path)} ({token['type']}) refers to a {tokens[target]['type']}"
            )
        return value_of(target, seen + [target])

    return {path: {**t, "value": value_of(path, [path])} for path, t in tokens.items()}


# ── Names ──────────────────────────────────────────────────────────────────────


def css_name(path):
    return "--lv-" + "-".join(path)


def camel(path):
    """Code name: colors drop their group (color.text-muted -> textMuted), the rest keep it."""
    parts = path[1:] if path[0] == "color" else path
    words = [w for p in parts for w in p.split("-")]
    return words[0] + "".join(w[:1].upper() + w[1:] for w in words[1:])


def number(text, unit):
    if not text.endswith(unit):
        raise TokenError(f"expected a value in {unit}, got {text}")
    n = float(text[: -len(unit)])
    return int(n) if n.is_integer() else n


def fmt(n):
    return repr(n) if isinstance(n, float) else str(n)


# ── Outputs ────────────────────────────────────────────────────────────────────


def css(tokens):
    lines = [f"/* {HEADER} */", ":root {"]
    for path, t in tokens.items():
        v = t["value"]
        if t["type"] == "fontFamily":
            v = ", ".join(f"'{f}'" if " " in f else f for f in v)
        elif t["type"] == "cubicBezier":
            v = "cubic-bezier(" + ", ".join(fmt(x) for x in v) + ")"
        lines.append(f"  {css_name(path)}: {v};")
    return "\n".join(lines + ["}", ""])


# QML reads a property called on<Something> as a signal handler, so those get another name there
QML_RENAMES = {"onAccent": "textOnAccent"}


def qml_name(path):
    name = camel(path)
    name = QML_RENAMES.get(name, name)
    if re.match(r"on[A-Z]", name):
        raise TokenError(
            f"{'.'.join(path)} would be '{name}' in QML, a signal handler name: add it to QML_RENAMES"
        )
    return name


def qml(tokens):
    lines = [f"// {HEADER}", "pragma Singleton", "import QtQuick", "", "QtObject {"]
    for path, t in tokens.items():
        name, v, kind = qml_name(path), t["value"], t["type"]
        if kind == "color":
            line = f'readonly property color {name}: "{v}"'
        elif kind == "dimension":
            line = f"readonly property real {name}: {fmt(number(v, 'px'))}"
        elif kind == "duration":
            line = f"readonly property int {name}: {fmt(number(v, 'ms'))}"
        elif kind == "fontFamily":
            line = f'readonly property string {name}: "{v[0]}"'
        elif kind == "fontWeight":
            line = f"readonly property int {name}: {v}"
        elif kind == "cubicBezier":
            # Easing.BezierSpline takes the control points and the end point
            line = f"readonly property var {name}: [{', '.join(fmt(x) for x in v)}, 1, 1]"
        elif kind == "number":
            line = f"readonly property real {name}: {fmt(v)}"
        else:
            raise TokenError(f"no QML output for type {kind}")
        lines.append("    " + line)
    lines += [
        "",
        "    // The mixes every piece uses (design/DESIGN.md Color, Edges), so none is mixed by hand",
    ]
    for name, base, opacity in TINTS:
        rgb = base if base.startswith("#") else tokens[("color", base)]["value"]
        alpha = round(tokens[("opacity", opacity)]["value"] * 255)
        lines.append(f'    readonly property color {name}: "#{alpha:02x}{rgb.lstrip("#")}"')
    return "\n".join(lines + ["}", ""])


# Derived colors in Theme.qml: (name, base color token or hex, opacity token)
TINTS = [
    ("hoverTint", "text", "hover"),
    ("selectionTint", "fog", "selection"),
]


def kotlin(tokens):
    lines = [
        f"// {HEADER}",
        "package dev.verginelli.levves",
        "",
        "import androidx.compose.animation.core.CubicBezierEasing",
        "import androidx.compose.ui.graphics.Color",
        "import androidx.compose.ui.unit.dp",
        "",
        "object Levves {",
    ]
    for path, t in tokens.items():
        name, v, kind = camel(path), t["value"], t["type"]
        if kind == "color":
            line = f"val {name} = Color(0xFF{v[1:].upper()})"
        elif kind == "dimension":
            line = f"val {name} = {fmt(number(v, 'px'))}.dp"
        elif kind == "duration":
            line = f"const val {name} = {fmt(number(v, 'ms'))}"
        elif kind == "fontFamily":
            line = f'const val {name} = "{v[0]}"'
        elif kind == "fontWeight":
            line = f"const val {name} = {v}"
        elif kind == "cubicBezier":
            line = f"val {name} = CubicBezierEasing({', '.join(f'{float(x)}f' for x in v)})"
        elif kind == "number":
            line = f"const val {name} = {float(v)}f"
        else:
            raise TokenError(f"no Kotlin output for type {kind}")
        lines.append("    " + line)
    return "\n".join(lines + ["}", ""])


def python(tokens):
    data = {".".join(path): t["value"] for path, t in tokens.items()}
    return (
        f'"""{HEADER}"""\n\nTOKENS = {json.dumps(data, indent=4)}\n\n\n'
        "def color(name):\n"
        '    """A color by its name without the group: color("text-muted"), color("terminal.cyan")."""\n'
        '    return TOKENS["color." + name]\n'
    )


def python_pieces(pieces=PY_PIECES):
    """The hand-written Python pieces, copied next to levves_tokens.py so one sys.path entry finds both."""
    return {
        path.name: f"# Copied from design/python/{path.name} by design/build/build.py. Don't edit here.\n"
        + path.read_text()
        for path in sorted(pieces.glob("*.py"))
    }


def android(tokens):
    """Colors as Android resources, for XML themes that can't read Kotlin."""
    lines = ['<?xml version="1.0" encoding="utf-8"?>', f"<!-- {HEADER} -->", "<resources>"]
    for path, t in tokens.items():
        if t["type"] == "color":
            name = "levves_" + "_".join(p.replace("-", "_") for p in path[1:])
            lines.append(f'    <color name="{name}">{t["value"]}</color>')
    return "\n".join(lines + ["</resources>", ""])


def qml_module(tokens, pieces=QML_PIECES):
    """The Levves QML module: Theme, the hand-written pieces and the qmldir."""
    files = {"Theme.qml": qml(tokens)}
    qmldir = ["module Levves", "singleton Theme 1.0 Theme.qml"]
    for path in sorted(pieces.glob("*.qml")):
        files[path.name] = (
            f"// Copied from design/qml/{path.name} by design/build/build.py. Don't edit here.\n"
            + path.read_text()
        )
        qmldir.append(f"{path.stem} 1.0 {path.name}")
    files["qmldir"] = "\n".join(qmldir) + "\n"
    return {f"qml/Levves/{name}": text for name, text in files.items()}


def outputs(tokens):
    return {
        "tokens.css": css(tokens),
        **qml_module(tokens),
        "kotlin/Levves.kt": kotlin(tokens),
        "levves_tokens.py": python(tokens),
        **python_pieces(),
        "android/res/values/levves_colors.xml": android(tokens),
    }


def main(argv):
    try:
        files = outputs(resolve(flatten(load())))
    except TokenError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    if "--check" in argv:
        stale = [
            name
            for name, text in files.items()
            if not (DIST / name).exists() or (DIST / name).read_text() != text
        ]
        for name in stale:
            print(f"out of date: design/dist/{name}", file=sys.stderr)
        if stale:
            print("run: python3 design/build/build.py", file=sys.stderr)
        return 1 if stale else 0
    for name, text in files.items():
        target = DIST / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text)
    print(f"wrote {len(files)} files to design/dist/")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
