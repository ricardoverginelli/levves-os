#!/usr/bin/env python3
"""Write the cheat sheet's data (sheet.json) into the installed script as
contents/ui/sheet.js (with palette.json), without the rows meant for other machines: a row's third
item names a repo folder, and its .only-on file lists the hostnames it's for.

Usage: build.py <installed script folder>   (apply.sh runs it after copying)
"""
import json
import socket
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[3]  # linux/plasma/kwin/leaves-cheatsheet -> repo root


def for_this_machine(folder):
    only_on = REPO / folder / ".only-on"
    if not only_on.exists():
        return True
    hosts = [line.strip() for line in only_on.read_text().splitlines()
             if line.strip() and not line.startswith("#")]
    return socket.gethostname() in hosts


sections = json.loads((HERE / "sheet.json").read_text())["sections"]
for section in sections:
    section["rows"] = [row[:2] for row in section["rows"] if len(row) < 3 or for_this_machine(row[2])]

# KWin's QML has the system color scheme, not the Leaves one, so the palette comes along
palette = json.loads((REPO / "linux/plasma/palette.json").read_text())

dest = Path(sys.argv[1]) / "contents/ui/sheet.js"
dest.write_text(".pragma library\n// Generated by build.py from sheet.json and palette.json\n"
                + "var sections = " + json.dumps(sections, indent=1, ensure_ascii=False) + ";\n"
                + "var palette = " + json.dumps(palette, indent=1) + ";\n")
