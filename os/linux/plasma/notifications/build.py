#!/usr/bin/env python3
"""Install the Leaves notifications (org.leaves.notifications): Plasma's own
notifications applet QML with our changes (patches.py), on top of the stock
applet's C++ side, the same way as the Leaves tray (../tray/build.py).

The popups are created by the applet's Globals singleton, which Plasma compiles
into its module; a copy of the QML alone would still show stock popups. So the
package carries its own Globals (global/qmldir) and every file is rewired from
the module's Globals to it. global/Palette.qml holds palette.json for the patches.

top-bar.js puts this applet in the Leaves tray in place of the stock one (never
both: each would show every popup). If a patch no longer matches (a Plasma
update changed the QML), the package is removed and the tray keeps the stock
applet; update patches.py for the new version. Prints "changed" when the
installed package changed.
"""
import json
import re
import shutil
import subprocess
import sys
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.dont_write_bytecode = True  # no __pycache__ in the repo
sys.path.insert(0, str(HERE))
import patches  # noqa: E402

ID = "org.leaves.notifications"
STOCK = "org.kde.plasma.notifications"
DEST = Path.home() / ".local/share/plasma/plasmoids" / ID
CACHE = Path.home() / ".cache/leaves/notifications"
PALETTE = HERE.parent / "palette.json"
UPSTREAM = "https://raw.githubusercontent.com/KDE/plasma-workspace/v{version}/applets/notifications/{path}"
# The QML files of applets/notifications/CMakeLists.txt
QML = ["main", "CompactRepresentation", "DraggableDelegate", "FullRepresentation", "NotificationPopup",
       "global/Globals", "global/PulseAudio",
       "delegates/BaseDelegate", "delegates/DelegateHistory", "delegates/DelegateHistoryGrouped",
       "delegates/DelegatePopup",
       "components/ActionContainer", "components/Body", "components/DraggableFileArea",
       "components/EditContextMenu", "components/FooterLoader", "components/HeadingButtons",
       "components/Icon", "components/JobDetails", "components/JobIconItem", "components/JobItem",
       "components/ModelInterface", "components/NotificationHeader", "components/NotificationReplyField",
       "components/SpeedChart", "components/Summary", "components/ThumbnailStrip"]

QMLDIR = """singleton Globals 1.0 Globals.qml
singleton Palette 1.0 Palette.qml
PulseAudio 1.0 PulseAudio.qml
"""


def plasma_version():
    out = subprocess.run(["plasmashell", "--version"], capture_output=True, text=True).stdout
    return out.split()[-1]


def fetch(version):
    """Upstream files for this version, cached so later runs work offline."""
    src = CACHE / version
    for path in ["metadata.json"] + [f"{q}.qml" for q in QML]:
        target = src / path
        if not target.exists():
            target.parent.mkdir(parents=True, exist_ok=True)
            with urllib.request.urlopen(UPSTREAM.format(version=version, path=path), timeout=30) as r:
                target.write_bytes(r.read())
    return src


def palette_qml():
    """palette.json as a QML singleton: Leaves.Palette.textMuted etc."""
    palette = json.loads(PALETTE.read_text())
    lines = ["pragma Singleton", "", "import QtQuick", "",
             "// Generated by notifications/build.py from palette.json", "QtObject {"]
    for key, value in palette.items():
        if isinstance(value, str) and value.startswith("#"):
            name = re.sub(r"-(\w)", lambda m: m.group(1).upper(), key)
            if name == "onAccent":
                name = "textOnAccent"  # QML reads on* properties as signal handlers
            lines.append(f'    readonly property color {name}: "{value}"')
    # Hover on neutral surfaces: text at 6% over them (DESIGN.md Mood)
    lines.append(f'    readonly property color hover: "#0f{palette["text"][1:]}"')
    lines.append("}")
    return "\n".join(lines) + "\n"


def use_leaves_globals(files):
    """Point every file at our Globals instead of the compiled one, and import
    global/ (as Leaves) where Leaves.Globals or Leaves.Palette is used."""
    for name, text in files.items():
        if not name.endswith(".qml") or "/global/" in name:
            continue
        text = re.sub(r"(?<![\w.])(Notifications|NotificationsApplet)\.Globals\b", "Leaves.Globals", text)
        if re.search(r"\bLeaves\.(Globals|Palette)\b", text):
            depth = name.count("/") - 2  # contents/ui/X.qml is depth 0
            imports = list(re.finditer(r"^import .*\n", text, re.M))
            line = f'import "{"../" * depth}global" as Leaves\n'
            text = text[:imports[-1].end()] + line + text[imports[-1].end():]
        files[name] = text


def snapshot(path):
    return {p.relative_to(path): p.read_bytes() for p in path.rglob("*") if p.is_file()} if path.exists() else {}


def main():
    version = plasma_version()
    before = snapshot(DEST)
    try:
        src = fetch(version)
        files = {f"contents/ui/{q}.qml": (src / f"{q}.qml").read_text() for q in QML}
        patches.apply(files)
        use_leaves_globals(files)
        files["contents/ui/global/qmldir"] = QMLDIR
        files["contents/ui/global/Palette.qml"] = palette_qml()
        metadata = json.loads((src / "metadata.json").read_text())
        metadata["KPackageStructure"] = "Plasma/Applet"
        metadata["KPlugin"]["Id"] = ID
        metadata["KPlugin"]["Name"] = "Leaves Notifications"
        # The tray turns on applets enabled by default; top-bar.js turns this
        # one on and the stock one off instead, so both never run together
        metadata["KPlugin"]["EnabledByDefault"] = False
        # Use the stock applet's C++ code (see the same line in ../tray/build.py)
        metadata["X-Plasma-RootPath"] = f"../applets/{STOCK}"
        files["metadata.json"] = json.dumps(metadata, indent=1, ensure_ascii=False)
    except (patches.PatchError, OSError) as e:
        shutil.rmtree(DEST, ignore_errors=True)
        print(f"Leaves notifications NOT installed for Plasma {version} ({e}); the tray uses the stock ones",
              file=sys.stderr)
    else:
        shutil.rmtree(DEST, ignore_errors=True)
        for rel, text in files.items():
            (DEST / rel).parent.mkdir(parents=True, exist_ok=True)
            (DEST / rel).write_text(text)
    if snapshot(DEST) != before:
        print("changed")


main()
